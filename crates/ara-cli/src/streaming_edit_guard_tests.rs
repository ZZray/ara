fn event(streaming: bool, files: Value, name: &str) -> AgentEvent {
    AgentEvent::ToolStreamUpdate {
        tool_call_id: "call-edit-1".into(),
        tool_name: name.into(),
        update: json!({"generation":1,"streaming":streaming,"files":files}),
    }
}

#[tokio::test]
async fn fixed_streaming_edit_abort_and_generated_guard_group() {
    let cwd = tempfile::tempdir().unwrap();
    std::fs::write(cwd.path().join("sample.txt"), "alpha\n").unwrap();
    let tool = EditTool::new(ToolContext::new(cwd.path()).with_edit(ara_edit::EditMode::Patch, true));
    let guard = Arc::new(StreamingEditGuard::new(tool.streaming_policy(), true));
    let aborts = Arc::new(std::sync::atomic::AtomicUsize::new(0));
    let seen = Arc::new(Mutex::new(Vec::new()));
    let g = guard.clone();
    let a = aborts.clone();
    let s = seen.clone();
    let mut stream = tool
        .open_arg_stream(ToolArgStreamInit {
            tool_call_id: "native-stream".into(),
            tool_name: "edit".into(),
            custom_wire_name: None,
            emit: Arc::new(move |update| {
                if g.maybe_abort(&AgentEvent::ToolStreamUpdate {
                    tool_call_id: "native-stream".into(),
                    tool_name: "edit".into(),
                    update: update.clone(),
                })
                .is_some()
                {
                    a.fetch_add(1, Ordering::SeqCst);
                }
                s.lock().unwrap().push(update);
            }),
        })
        .unwrap()
        .unwrap();
    let args = json!({"path":"sample.txt","edits":[{"diff":"@@\n-missing\n+replacement\n"}]});
    let encoded = args.to_string();
    for delta in encoded.as_bytes().chunks(7) {
        stream.push(std::str::from_utf8(delta).unwrap()).unwrap();
    }
    stream.end(args.as_object().unwrap()).unwrap();
    tokio::time::timeout(std::time::Duration::from_secs(5), async {
        loop {
            if seen.lock().unwrap().last().is_some_and(|batch| batch["streaming"] == false) {
                break;
            }
            tokio::time::sleep(std::time::Duration::from_millis(1)).await;
        }
    })
    .await
    .unwrap();
    assert_eq!(aborts.load(Ordering::SeqCst), 1, "B-b5baec43d8 final native preview aborts once");
    assert!(guard.abort_triggered());
    assert_eq!(seen.lock().unwrap().last().unwrap()["streaming"], false);
    assert_eq!(std::fs::read_to_string(cwd.path().join("sample.txt")).unwrap(), "alpha\n", "preview never writes");
    stream.cancel().unwrap();

    let guard = StreamingEditGuard::new(tool.streaming_policy(), true);
    let final_event =
        event(false, json!([{"path":"ok.ts"},{"path":"broken.ts","error":"Failed to find expected lines"}]), "edit");
    let abort = guard.maybe_abort(&final_event).unwrap();
    assert_eq!(abort.path, "broken.ts", "B-1f3d027622 selects the first native file error");
    assert!(!abort.generated);
    assert!(guard.maybe_abort(&final_event).is_none(), "same turn only aborts once");
    let transient = StreamingEditGuard::new(tool.streaming_policy(), true);
    assert!(
        transient.maybe_abort(&event(true, json!([{"path":"broken.ts","error":"partial input"}]), "edit")).is_none(),
        "B-8d0328bd31"
    );
    assert!(!transient.abort_triggered());
    assert!(
        transient.maybe_abort(&event(false, json!([{"path":"a.ts","error":"bad"}]), "read")).is_none(),
        "B-a51faa58ce non-edit"
    );
    let disabled = StreamingEditGuard::new(tool.streaming_policy(), false);
    assert!(disabled.maybe_abort(&final_event).is_none(), "B-a51faa58ce disabled");
    guard.reset();
    assert!(guard.maybe_abort(&final_event).is_some(), "reset permits later final preview");

    std::fs::write(cwd.path().join("generated.ts"), "// Code generated by sqlc. DO NOT EDIT.\nexport const x = 1;\n")
        .unwrap();
    let partial = ara_ai::AssistantMessage {
        content: vec![ara_ai::AssistantBlock::ToolCall(ara_ai::ToolCall {
            id: "call-generated".into(),
            name: "edit".into(),
            arguments: json!({"path":"generated.ts","diff":""}).as_object().unwrap().clone(),
            ..Default::default()
        })],
        ..ara_ai::AssistantMessage::empty("openai-completions", "custom", "mock")
    };
    let typed = AgentEvent::MessageUpdate {
        message: ara_agent::AgentMessage::from_model(ara_ai::Message::Assistant(partial.clone())),
        event: AssistantMessageEvent::ToolcallStart { content_index: 0, partial: partial.clone() },
    };
    // B-192847dea0: old generated preCache abort is version-superseded.
    // b91 stream-guards.ts only consumes final native preview failures.
    assert!(run_precheck(&disabled,&typed,None).await.unwrap().is_none());
    assert!(!disabled.abort_triggered());
    let realm=crate::native_realm::NativeRealm::prepare().unwrap();
    let root=realm.values.heap().import_serde(&serde_json::to_value(ara_ai::Message::Assistant(partial)).unwrap()).unwrap();
    let original=root.clone();
    let actual=AgentEvent::ActualMessageUpdate {
        message:ara_agent::AgentMessage::from_graph(root.clone(),None).unwrap(),
        event:AssistantMessageEvent::ToolcallStart {content_index:realm.values.heap().number(0.0).unwrap(),partial:root},
    };
    assert!(run_precheck(&disabled,&actual,Some(&realm.values)).await.unwrap().is_none());
    let AgentEvent::ActualMessageUpdate {message,..}=actual else {unreachable!()};
    let ara_agent::AgentMessageBody::Graph(after)=message.body_snapshot() else {unreachable!()};
    assert!(after.same_identity(&original),"removed precheck retains original partial owner");
    let noop=StreamingEditGuard::new(tool.streaming_policy(),true);
    assert!(noop.maybe_abort(&event(false,json!([{"path":"sample.txt","error":"No changes would be made to sample.txt (replace)"}]),"edit")).is_none());
    assert!(!noop.abort_triggered());
    let mixed=event(false,json!([
        {"path":"sample.txt","error":"No changes would be made to sample.txt"},
        {"path":"broken.ts","error":"expected lines missing"}
    ]),"edit");
    assert_eq!(noop.maybe_abort(&mixed).unwrap().path,"broken.ts","skip only source no-op prefix and retain actual errors");
    native_noop_preview_continues(cwd.path()).await;
    generated_abort_loop(cwd.path()).await;
    final_preview_abort_loop(cwd.path()).await;
}

// This fixture used to wait only for cancel. The b91 generated path has an
// ordinary error receipt, so its controlled model must close the tool call and
// provide the next response; waiting for a removed precheck would deadlock.
struct GeneratedProvider {
    partial:ara_ai::AssistantMessage,
    signal:Arc<Mutex<Option<tokio_util::sync::CancellationToken>>>,
    follow_up:bool,
    calls:Arc<std::sync::atomic::AtomicUsize>,
    saw_error:Arc<std::sync::atomic::AtomicBool>,
}
impl ara_ai::ModelProvider for GeneratedProvider {
    fn stream(&self,_:&ara_ai::Model,context:&ara_ai::Context,options:ara_ai::CallOptions)->ara_ai::AssistantStream {
        let index=self.calls.fetch_add(1,Ordering::SeqCst);
        let (sink,stream)=ara_ai::event::EventSink::channel();
        if index>0 {
            assert!(self.follow_up,"failed final preview must not request another model turn");
            let error=context.messages.iter().find_map(|message|match message {
                ara_ai::Message::ToolResult(result) if result.tool_call_id=="call_edit_regression"=>Some(result),_=>None,
            }).expect("generated refusal reaches the next actual model request");
            assert!(error.is_error);assert!(serde_json::to_string(error).unwrap().contains("Cannot modify auto-generated file"));
            assert!(!self.signal.lock().unwrap().as_ref().unwrap().is_cancelled(),"generated error reached another request before any abort");
            self.saw_error.store(true,Ordering::SeqCst);
            let mut message=ara_ai::AssistantMessage::empty("openai-completions","custom","mock");
            message.content.push(ara_ai::AssistantBlock::text("Handled tool refusal."));message.stop_reason=ara_ai::StopReason::Stop;
            tokio::spawn(async move {sink.push(AssistantMessageEvent::Done {reason:ara_ai::StopReason::Stop,message}).await;});
            return stream;
        }
        *self.signal.lock().unwrap()=Some(options.cancel.clone());
        let mut partial=self.partial.clone();let follow_up=self.follow_up;
        tokio::spawn(async move {
            sink.push(AssistantMessageEvent::Start {partial:partial.clone()}).await;
            sink.push(AssistantMessageEvent::ToolcallStart {content_index:0,partial:partial.clone()}).await;
            let call=partial.content[0].as_tool_call().unwrap().clone();
            sink.push(AssistantMessageEvent::ToolcallDelta {content_index:0,delta:Value::Object(call.arguments.clone()).to_string(),partial:partial.clone()}).await;
            sink.push(AssistantMessageEvent::ToolcallEnd {content_index:0,tool_call:call,partial:partial.clone()}).await;
            if follow_up {
                partial.stop_reason=ara_ai::StopReason::ToolUse;
                sink.push(AssistantMessageEvent::Done {reason:ara_ai::StopReason::ToolUse,message:partial}).await;
            } else {
                options.cancel.cancelled().await;partial.stop_reason=ara_ai::StopReason::Aborted;
                sink.push(AssistantMessageEvent::Error {reason:ara_ai::StopReason::Aborted,error:partial}).await;
            }
        });stream
    }
}
struct ObservedEditTool {
    edit: EditTool,
    executions: Arc<std::sync::atomic::AtomicUsize>,
}
#[async_trait::async_trait]
impl AgentTool for ObservedEditTool {
    fn definition(&self) -> ara_ai::Tool {
        self.edit.definition()
    }
    fn open_arg_stream(
        &self,
        init: ToolArgStreamInit,
    ) -> Result<Option<Box<dyn ara_agent::ToolArgStream>>, ara_agent::ToolError> {
        self.edit.open_arg_stream(init)
    }
    async fn execute(
        &self,
        id: &str,
        args: ara_ai::JsonObject,
        cancel: tokio_util::sync::CancellationToken,
        update: ara_agent::UpdateFn,
    ) -> Result<ara_agent::ToolOutput, ara_agent::ToolError> {
        self.executions.fetch_add(1, Ordering::SeqCst);
        self.edit.execute(id, args, cancel, update).await
    }
}
async fn generated_abort_loop(cwd: &std::path::Path) {
    guarded_abort_loop(cwd, true).await;
}
async fn final_preview_abort_loop(cwd: &std::path::Path) {
    guarded_abort_loop(cwd, false).await;
}
async fn guarded_abort_loop(cwd: &std::path::Path, generated: bool) {
    let context = ToolContext::new(cwd).with_edit(ara_edit::EditMode::Patch, true);
    let executions = Arc::new(std::sync::atomic::AtomicUsize::new(0));
    let tool = Arc::new(ObservedEditTool { edit: EditTool::new(context), executions: executions.clone() });
    let signal = Arc::new(Mutex::new(None));
    let partial = ara_ai::AssistantMessage {
        content:vec![ara_ai::AssistantBlock::ToolCall(ara_ai::ToolCall {
            id:"call_edit_regression".into(), name:"edit".into(), arguments:json!({"path":if generated {"generated.ts"} else {"sample.txt"},"edits":[{"diff":"@@\n-missing\n+replacement\n"}]}).as_object().unwrap().clone(), ..Default::default()
        })], ..ara_ai::AssistantMessage::empty("openai-completions", "custom", "mock")
    };
    let cancel = tokio_util::sync::CancellationToken::new();
    let guard=Arc::new(StreamingEditGuard::new(tool.edit.streaming_policy(),!generated));
    let events=ara_agent::RecordingSink::default();
    let sink=crate::streaming_edit_sink::StreamingEditSink::new(&events,Some(guard.clone()),None,cancel.clone());
    let calls=Arc::new(std::sync::atomic::AtomicUsize::new(0));
    let saw_error=Arc::new(std::sync::atomic::AtomicBool::new(false));
    let config = ara_agent::AgentConfig {
        model: ara_ai::Model {
            id: "mock".into(),
            api: "openai-completions".into(),
            provider: "custom".into(),
            base_url: String::new(),
            reasoning: false,
            max_tokens: None,
            context_window: None,
            tokenizer: None,
        },
        provider: Arc::new(GeneratedProvider {partial,signal:signal.clone(),follow_up:generated,calls:calls.clone(),saw_error:saw_error.clone()}),
        system_prompt: vec!["Test".into()],
        tools: vec![tool],
        tool_choice: None,
        max_tokens: None,
        temperature: None,
        deadline: None,
        max_model_calls: Some(if generated {2} else {1}),
        hooks: Arc::new(ara_agent::NoHooks),
        interrupt_mode: ara_agent::InterruptMode::Immediate,
    };
    let report = tokio::time::timeout(
        std::time::Duration::from_secs(5),
        ara_agent::agent_loop(
            vec![ara_ai::Message::User(ara_ai::UserMessage::text("apply patch"))],
            &mut Vec::new(),
            &config,
            &cancel,
            &sink,
        ),
    )
    .await
    .unwrap();
    let messages=report.model_messages().unwrap();
    let last=messages.iter().rev().find_map(ara_ai::Message::as_assistant).unwrap();
    let receipts:Vec<_>=messages.iter().filter_map(|message|match message {ara_ai::Message::ToolResult(result)=>Some(result),_=>None}).collect();
    assert_eq!(receipts.len(),1);assert!(receipts[0].is_error);
    let encoded=serde_json::to_string(receipts[0]).unwrap();
    if generated {
        assert_eq!(calls.load(Ordering::SeqCst),2,"ordinary generated tool error permits the next model turn");
        assert!(saw_error.load(Ordering::SeqCst));assert!(!cancel.is_cancelled());
        // Normal Run teardown may cancel a child signal after successful completion.
        // The provider above observes it live before the second request.
        assert_eq!(last.stop_reason,ara_ai::StopReason::Stop);
        assert_eq!(executions.load(Ordering::SeqCst),1,"actual Edit.execute owns generated refusal");
        assert!(encoded.contains("Cannot modify auto-generated file"));
        assert_ne!(receipts[0].details.as_ref().and_then(|details|details.get("__synthetic")),Some(&Value::Bool(true)));
        assert_eq!(std::fs::read_to_string(cwd.join("generated.ts")).unwrap(),"// Code generated by sqlc. DO NOT EDIT.\nexport const x = 1;\n");
    } else {
        assert!(guard.abort_triggered());assert!(signal.lock().unwrap().as_ref().unwrap().is_cancelled());
        assert_eq!(last.stop_reason,ara_ai::StopReason::Aborted);
        assert_eq!(executions.load(Ordering::SeqCst),0,"actionable final preview failure aborts before execute");
        assert_eq!(receipts[0].details.as_ref().unwrap()["__synthetic"],true);
        assert_eq!(receipts[0].details.as_ref().unwrap()["executed"],false);
        assert!(encoded.contains("Streaming edit preview failed for sample.txt"),"production sink carries source tool-scoped diagnostic: {encoded}");
        assert_eq!(std::fs::read_to_string(cwd.join("sample.txt")).unwrap(),"alpha\n");
    }

}

async fn run_precheck(
    guard: &StreamingEditGuard,
    event: &AgentEvent,
    values: Option<&SessionValues>,
) -> Result<Option<StreamingEditAbort>, ActualProviderError> {
    match guard.pre_cache(event, values)? {
        Some(check) => guard.check_generated(check).await,
        None => Ok(None),
    }
}

async fn native_noop_preview_continues(cwd:&std::path::Path) {
    let tool=EditTool::new(ToolContext::new(cwd).with_edit(ara_edit::EditMode::Replace,true));
    let guard=Arc::new(StreamingEditGuard::new(tool.streaming_policy(),true));let observed=Arc::new(Mutex::new(Vec::<Value>::new()));
    let current=guard.clone();let seen=observed.clone();
    let mut stream=tool.open_arg_stream(ToolArgStreamInit {
        tool_call_id:"actual-native-noop".into(),tool_name:"edit".into(),custom_wire_name:None,
        emit:Arc::new(move |update| {
            assert!(current.maybe_abort(&AgentEvent::ToolStreamUpdate {tool_call_id:"actual-native-noop".into(),tool_name:"edit".into(),update:update.clone()}).is_none(),"native byte-identical preview is non-actionable");
            seen.lock().unwrap().push(update);
        }),
    }).unwrap().unwrap();
    let args=json!({"path":"sample.txt","old_string":"alpha","new_string":"alpha"});stream.push(&args.to_string()).unwrap();stream.end(args.as_object().unwrap()).unwrap();
    tokio::time::timeout(std::time::Duration::from_secs(5),async {
        while !observed.lock().unwrap().last().is_some_and(|update|update["streaming"]==false) {
            tokio::time::sleep(std::time::Duration::from_millis(1)).await;
        }
    }).await.unwrap();
    let updates=observed.lock().unwrap();let final_preview=updates.last().unwrap();
    assert!(final_preview["files"][0]["error"].as_str().unwrap().starts_with("No changes would be made"));
    assert!(!guard.abort_triggered());assert_eq!(std::fs::read_to_string(cwd.join("sample.txt")).unwrap(),"alpha\n");
    drop(updates);stream.cancel().unwrap();
}
