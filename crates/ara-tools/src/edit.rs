/// Settings defaults `edit.fuzzyMatch`, `edit.fuzzyThreshold`,
/// `edit.enforceSeenLines`, `edit.blockAutoGenerated`.
pub const ALLOW_FUZZY: bool = true;
pub const FUZZY_THRESHOLD: f64 = 0.95;
pub const ENFORCE_SEEN_LINES: bool = true;
pub const BLOCK_AUTO_GENERATED: bool = true;

/// Host-resolved immutable edit policy. Loading settings/environment belongs
/// to the Host; mode-dependent snapshots keep the existing Session EditStore.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct EditSettings {
    pub allow_fuzzy: bool,
    pub fuzzy_threshold: f64,
    pub enforce_seen_lines: bool,
    pub block_auto_generated: bool,
}

impl Default for EditSettings {
    fn default() -> Self {
        Self {
            allow_fuzzy: ALLOW_FUZZY,
            fuzzy_threshold: FUZZY_THRESHOLD,
            enforce_seen_lines: ENFORCE_SEEN_LINES,
            block_auto_generated: BLOCK_AUTO_GENERATED,
        }
    }
}

