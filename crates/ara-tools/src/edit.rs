//! `edit` tool (OMP `packages/coding-agent/src/edit/{index,schemas}.ts` and the
//! `EditSession` binding in `crates/pi-natives/src/edit.rs`, at
//! 596f2da7101178214aa27a753529d15e6b7ad91d).
//!
//! The edit engine is the vendored OMP `pi-edit` crate: every mode's parser,
//! matcher, staging, diff and model-facing text. This module is the host
//! part: it builds the session policy, feeds the finished arguments, and owns
//! the file writes (create, update, move, delete), including upstream's
//! "content did not change on disk" guard and the parse-regression warning.
//!
//! Intentional differences (data safety):
//! - Re-encoding a file that is not valid UTF-8 is refused while staging, so
//!   nothing is written (vendored `pi-edit` `FileRead::persist`, marked
//!   `ARA:`). Upstream decodes lossily and writes U+FFFD over every
//!   undecodable byte. Deletes are unaffected.
//! - Hashline `MV` onto an existing file is refused while staging (vendored
//!   patcher, patch mode's wording) unless the payload removed it earlier.
//!   Upstream overwrites it. patch/apply_patch keep their own upstream guard.
//! - A moved file keeps its permission bits (upstream recreates it with the
//!   default mode, dropping an executable bit).
//! - A failure after some files of the call changed names every effect that
//!   already happened (written files, a copied move, a possibly partial
//!   write), so a retry never runs blind.
//!
//! Updates are written in place like upstream (no temp-file rename), which
//! keeps symlinks, hard links and ownership intact.
//!
//! Not ported (open): streamed argument previews (`openArgStream`), LSP
//! write-through (format on write, diagnostics), the auto-repair model pass
//! (the warning variant of its note is kept), plan mode, `local://` and
//! `vault://` targets, ACP bridges, blackbox recording, approval tiers.

